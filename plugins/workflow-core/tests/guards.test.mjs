import assert from 'node:assert/strict';
import { join } from 'node:path';
import { after, describe, test } from 'node:test';
import { globToRegExp, splitSegments } from '../scripts/lib/guards.mjs';
import { cleanup, createProject, createWorkspace, runScript, writeFile } from './helpers.mjs';

after(cleanup);

const GUARDS = {
	protectedPaths: [
		{
			glob: 'be/postgres/migrations/*.js',
			when: 'tracked',
			message: 'Committed migration: add a new migration instead (db-migration skill).',
		},
		{
			glob: 'mobile/ios/**',
			message: 'Generated by expo prebuild --clean: change app.json / config plugins.',
		},
		{ glob: 'mobile/*.aab', message: 'Build artifact.' },
		{ glob: 'mobile/google-services.json', message: 'Credential file.' },
		{ glob: 'backend/.nx/**', message: 'Nx cache.' },
	],
	blockedCommands: [
		{
			regex:
				'^(npx\\s+)?(npm run (start_dev2?|start_ngrok|serve|serve_vite|android|ios|web)|npm start|expo start|nodemon|nx serve|react-scripts start)(\\s|$)',
			message: 'Dev servers are run by the user. Verify with typecheck/lint/tests.',
		},
		{
			regex: '^npm run test:unit(\\s|$)',
			cwd: 'ui',
			message: 'ui test:unit is Vitest watch mode: use npx vitest run [path].',
		},
		{
			regex: '^npm (run )?test(\\s|$)',
			cwd: 'fe',
			message: 'fe has no tests; npm test is CRA watch mode.',
		},
	],
};

const CONFIG = {
	version: 1,
	units: { be: { dir: 'be' }, ui: { dir: 'ui' }, fe: { dir: 'fe' }, mobile: { dir: 'mobile' } },
	guards: GUARDS,
};

function workspace() {
	return createWorkspace({
		config: CONFIG,
		repos: {
			be: { 'postgres/migrations/001-init.js': 'module.exports = {};\n' },
			ui: { 'src/a.ts': '' },
			fe: { 'src/a.js': '' },
			mobile: { 'app.json': '{}\n' },
		},
	});
}

const editHook = (w, file) =>
	runScript('guard-files.mjs', [], {
		root: w.root,
		input: JSON.stringify({ tool_input: { file_path: file } }),
	});

const bashHook = (w, command, cwd = w.root) =>
	runScript('guard-bash.mjs', [], {
		root: w.root,
		input: JSON.stringify({ tool_input: { command }, cwd }),
	});

describe('glob matcher', () => {
	const cases = [
		['a/**', 'a/x/y', true],
		['a/**', 'a', true],
		['a/**', 'ab/x', false],
		['a/**/b', 'a/b', true],
		['a/**/b', 'a/x/y/b', true],
		['**/b.js', 'b.js', true],
		['**/b.js', 'x/y/b.js', true],
		['mobile/*.aab', 'mobile/app.aab', true],
		['mobile/*.aab', 'mobile/x/app.aab', false],
		['a?.js', 'ab.js', true],
		['a?.js', 'a/.js', false],
		['be/postgres/migrations/*.js', 'be/postgres/migrations/001.js', true],
		['backend/.nx/**', 'backend/.nx/cache/x', true],
		['backend/.nx/**', 'backend/xnx/a', false],
	];
	for (const [glob, path, expected] of cases) {
		test(`${glob} ${expected ? 'matches' : 'does not match'} ${path}`, () => {
			assert.equal(globToRegExp(glob).test(path), expected);
		});
	}
});

describe('command segments', () => {
	test('splits on operators outside quotes', () => {
		assert.deepEqual(
			splitSegments('git status; npm start && echo "a; b" | cat & (cd ui || x)\nls'),
			['git status', 'npm start', 'echo "a; b"', 'cat', 'cd ui', 'x', 'ls']
		);
		assert.deepEqual(splitSegments('echo \'npm start\' && echo "x \\" && y"'), [
			"echo 'npm start'",
			'echo "x \\" && y"',
		]);
	});
});

describe('guard-files hook', () => {
	test('a tracked migration is blocked; a new one is allowed', () => {
		const w = workspace();
		const r = editHook(w, join(w.root, 'be/postgres/migrations/001-init.js'));
		assert.equal(r.status, 2);
		assert.equal(
			r.stderr,
			'Blocked: Committed migration: add a new migration instead (db-migration skill).\n'
		);
		assert.equal(editHook(w, join(w.root, 'be/postgres/migrations/002-next.js')).status, 0);
	});

	test('generated, artifact and cache paths are blocked even when new', () => {
		const w = workspace();
		assert.equal(editHook(w, join(w.root, 'mobile/ios/Podfile')).status, 2);
		assert.equal(editHook(w, 'mobile/ios/App/AppDelegate.swift').status, 2);
		assert.match(editHook(w, join(w.root, 'mobile/app-release.aab')).stderr, /Build artifact/);
		assert.match(editHook(w, join(w.root, 'backend/.nx/cache/a.json')).stderr, /Nx cache/);
		assert.equal(editHook(w, join(w.root, 'mobile/app.json')).status, 0);
		assert.equal(editHook(w, join(w.root, 'ui/src/a.ts')).status, 0);
	});

	test('files outside the project are allowed', () => {
		const w = workspace();
		writeFile(w.sandbox, 'mobile/ios/x', '');
		assert.equal(editHook(w, join(w.sandbox, 'mobile/ios/x')).status, 0);
	});

	test('no config or an invalid config fails open silently', () => {
		const p = createProject({ files: { 'a.ts': '' } });
		assert.equal(editHook(p, join(p.root, 'a.ts')).status, 0);
		writeFile(p.root, '.claude/workflow.config.json', '{"version": 1, "guards": 3}');
		const r = editHook(p, join(p.root, 'a.ts'));
		assert.equal(r.status, 0);
		assert.equal(r.stderr, '');
	});
});

describe('guard-bash hook', () => {
	const blocked = [
		['npm run start_dev', null],
		['npx nodemon src/index.ts', null],
		['git status; npm start', null],
		['cd ui && npm run test:unit', null],
		['npm run test:unit', 'ui'],
		['npm run test:unit -- src/a.test.ts', 'ui/src'],
		['npm test', 'fe'],
		['npm test --prefix fe', null],
		['cd fe; npm run test', null],
	];
	for (const [command, cwd] of blocked) {
		test(`blocks ${command}${cwd ? ` from ${cwd}` : ''}`, () => {
			const w = workspace();
			const r = bashHook(w, command, cwd ? join(w.root, cwd) : w.root);
			assert.equal(r.status, 2, r.stderr);
			assert.match(r.stderr, /^Blocked: /);
		});
	}

	const allowed = [
		['echo "npm start"', null],
		['npm run test:unit', 'be'],
		['npm run test:unit', null],
		['cd be && npm run test:unit', 'ui/..'],
		['npm run lint', 'ui'],
		['npm test', 'ui'],
		['grep -r "npm start" .', null],
	];
	for (const [command, cwd] of allowed) {
		test(`allows ${command}${cwd ? ` from ${cwd}` : ''}`, () => {
			const w = workspace();
			const r = bashHook(w, command, cwd ? join(w.root, cwd) : w.root);
			assert.equal(r.status, 0, r.stderr);
		});
	}

	test('a rule with cwd applies when the command names the dir', () => {
		const w = workspace();
		assert.equal(bashHook(w, 'npm run test:unit --prefix ./ui').status, 2);
		assert.equal(bashHook(w, 'npm run test:unit', join(w.root, 'be')).status, 0);
	});

	test('no guards configured exits 0', () => {
		const p = createProject({ config: { version: 1 }, files: { 'a.ts': '' } });
		assert.equal(bashHook(p, 'npm start').status, 0);
	});
});
